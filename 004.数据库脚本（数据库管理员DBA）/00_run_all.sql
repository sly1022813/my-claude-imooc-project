-- =====================================================
SELECT '>>> 步骤3/8: 创建索引...' AS status;
SOURCE 03_create_indexes.sql;

-- =====================================================
-- 步骤4：插入系统预设分类
-- =====================================================
SELECT '>>> 步骤4/8: 插入系统预设分类...' AS status;
SOURCE 04_system_categories.sql;

-- =====================================================
-- 步骤5：创建视图
-- =====================================================
SELECT '>>> 步骤5/8: 创建视图...' AS status;
SOURCE 05_views.sql;

-- =====================================================
-- 步骤6：创建存储过程
