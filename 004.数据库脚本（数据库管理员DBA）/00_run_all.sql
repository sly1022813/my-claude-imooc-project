-- 表数量统计
SELECT CONCAT('数据表数量: ', COUNT(*)) AS statistic
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'light_accounting';

-- 视图数量统计
SELECT CONCAT('视图数量: ', COUNT(*)) AS statistic
FROM information_schema.VIEWS
WHERE TABLE_SCHEMA = 'light_accounting';

-- 存储过程数量统计
SELECT CONCAT('存储过程数量: ', COUNT(*)) AS statistic
FROM information_schema.ROUTINES
WHERE ROUTINE_SCHEMA = 'light_accounting'
  AND ROUTINE_TYPE = 'PROCEDURE';

-- 函数数量统计
SELECT CONCAT('函数数量: ', COUNT(*)) AS statistic
FROM information_schema.ROUTINES
WHERE ROUTINE_SCHEMA = 'light_accounting'
  AND ROUTINE_TYPE = 'FUNCTION';

-- 分类统计
SELECT CONCAT('系统预设分类: ', COUNT(*)) AS statistic
FROM light_accounting.categories
WHERE user_id = 0;

-- 执行耗时
SELECT CONCAT('执行耗时: ', TIMESTAMPDIFF(SECOND, @start_time, NOW()), ' 秒') AS statistic;

SELECT '========================================' AS '';
SELECT ' 初始化脚本执行完毕' AS '';
SELECT '========================================' AS '';

