SELECT ' 轻记账数据库初始化脚本 v1.0.1' AS '';
SELECT ' 开始执行...' AS '';
SELECT '========================================' AS '';

-- 计时开始
SET @start_time = NOW();

-- =====================================================
-- 步骤1：创建数据库
-- =====================================================
SELECT '>>> 步骤1/8: 创建数据库...' AS status;
SOURCE 01_init_database.sql;

-- =====================================================
